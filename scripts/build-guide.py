def p(text, bold_prefix=None):
    para = doc.add_paragraph()
    if bold_prefix and text.startswith(bold_prefix):
        para.add_run(bold_prefix).bold = True; para.add_run(text[len(bold_prefix):])
    else: para.add_run(text)
    return para

def steps(lines):
    for i, text in enumerate(lines, 1):
        para = p(f'{i}  {text}')
        para.paragraph_format.left_indent = Inches(.04)
        para.paragraph_format.space_after = Pt(7)

fig_no = 0
def fig(name, caption, max_h=4.25, max_w=7.1):
    global fig_no
    image = SHOTS / (name + '.png')
    w, h = Image.open(image).size
    width = min(max_w, max_h*w/h)
    para = doc.add_paragraph(); para.alignment = WD_ALIGN_PARAGRAPH.CENTER
    para.paragraph_format.space_before = Pt(4)
    para.paragraph_format.space_after = Pt(2)
    para.paragraph_format.keep_with_next = True
    para.add_run().add_picture(str(image), width=Inches(width))
    fig_no += 1
    cap = doc.add_paragraph(f'图 {fig_no:02d}  {caption}', 'Caption')
    cap.alignment = WD_ALIGN_PARAGRAPH.CENTER
    cap.paragraph_format.space_after = Pt(10)

def table(headers, rows, widths):
    t = doc.add_table(rows=1, cols=len(headers)); t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for col, width in zip(t.columns, widths): col.width = Inches(width)
    for c, text in zip(t.rows[0].cells, headers): c.text = text
    for row in rows:
        for c, text in zip(t.add_row().cells, row): c.text = str(text)
    for i, row in enumerate(t.rows):
        for j, c in enumerate(row.cells):
            c.width = Inches(widths[j]); c.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
            pr = c._tc.get_or_add_tcPr()
            borders = OxmlElement('w:tcBorders')
            for edge in ['top','left','bottom','right']:
                b = OxmlElement('w:'+edge); b.set(qn('w:val'),'single'); b.set(qn('w:sz'),'4'); b.set(qn('w:color'),'D9D9D9'); borders.append(b)
            pr.append(borders)
            margins = OxmlElement('w:tcMar')
            for edge in ['top','bottom','left','right']:
                e = OxmlElement('w:'+edge); e.set(qn('w:w'),'85'); e.set(qn('w:type'),'dxa'); margins.append(e)
            pr.append(margins)
            if i == 0:
                shd = OxmlElement('w:shd'); shd.set(qn('w:fill'),'E7EEF4'); pr.append(shd)
            for para in c.paragraphs:
                para.paragraph_format.space_after = Pt(0); para.paragraph_format.line_spacing = 1.05
                for r in para.runs: r.font.size = Pt(10); r.bold = i == 0
    repeat = OxmlElement('w:tblHeader'); t.rows[0]._tr.get_or_add_trPr().append(repeat)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t

